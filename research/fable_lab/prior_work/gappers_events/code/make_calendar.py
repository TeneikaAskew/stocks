"""Report-day calendar for 2025-03-03 to 2026-11-10. Dates typed from the agencies' published schedules
(see calendar/SOURCES.md). Writes calendar/report_days.csv: date,event,time_et,tier,note
Usage: python3 make_calendar.py"""
import csv, os
HERE = os.path.dirname(os.path.abspath(__file__))
E = []
def add(ev, tier, time, dates, note=''):
    for d in dates.split():
        E.append((d, ev, time, tier, note))
# BLS Employment Situation (jobs), 08:30
add('NFP', 1, '08:30', '2025-03-07 2025-04-04 2025-05-02 2025-06-06 2025-07-03 2025-08-01 2025-09-05 2025-11-20 2025-12-16 '
    '2026-01-09 2026-02-11 2026-03-06 2026-04-03 2026-05-08 2026-06-05 2026-07-02 2026-08-07 2026-09-04 2026-10-02 2026-11-06')
# BLS CPI, 08:30
add('CPI', 1, '08:30', '2025-03-12 2025-04-10 2025-05-13 2025-06-11 2025-07-15 2025-08-12 2025-09-11 2025-10-24 2025-12-18 '
    '2026-01-13 2026-02-13 2026-03-11 2026-04-10 2026-05-12 2026-06-10 2026-07-14 2026-08-12 2026-09-11 2026-10-14 2026-11-10')
# BEA Personal Income and Outlays (PCE), 08:30 unless noted
add('PCE', 1, '08:30', '2025-03-28 2025-05-30 2025-06-27 2025-07-31 2025-08-29 2025-09-26 '
    '2026-02-20 2026-03-13 2026-04-09 2026-04-30 2026-05-28 2026-06-25 2026-07-30 2026-08-26 2026-09-30 2026-10-29')
add('PCE', 1, '10:00', '2025-04-30 2025-12-05 2026-01-22', 'released at 10:00, not 08:30')
# FOMC decision days, statement 14:00
add('FOMC', 1, '14:00', '2025-03-19 2025-05-07 2025-06-18 2025-07-30 2025-09-17 2025-10-29 2025-12-10 '
    '2026-01-28 2026-03-18 2026-04-29 2026-06-17 2026-07-29 2026-09-16 2026-10-28')
# Second tier 08:30 releases
add('PPI', 2, '08:30', '2025-03-13 2025-04-11 2025-05-15 2025-06-12 2025-07-16 2025-08-14 2025-09-10 2025-11-25 '
    '2026-01-14 2026-01-30 2026-02-27 2026-03-18 2026-04-14 2026-05-13 2026-06-11 2026-07-15 2026-08-13 2026-09-10 2026-10-15')
add('GDP', 2, '08:30', '2025-03-27 2025-04-30 2025-05-29 2025-06-26 2025-07-30 2025-08-28 2025-09-25 2025-12-23 '
    '2026-01-22 2026-02-20 2026-03-13 2026-04-09 2026-04-30 2026-05-28 2026-06-25 2026-07-30 2026-08-26 2026-09-30 2026-10-29')
add('RETAIL', 2, '08:30', '2026-01-14 2026-02-10 2026-03-06 2026-04-01 2026-04-21 2026-05-14 2026-06-17 2026-07-16 2026-08-14 '
    '2026-09-16 2026-10-15')
add('RETAIL', 2, '08:30', '2025-03-17 2025-04-16 2025-05-15 2025-06-17 2025-07-17 2025-08-15 2025-09-16 2025-11-25 2025-12-16',
    '2025 dates not from a fetched page (Census 2025 list was not reachable); checked only by the 08:30 volume spike')
E = sorted(e for e in E if '2025-03-03' <= e[0] <= '2026-11-10')
out = os.path.join(HERE, '..', 'calendar', 'report_days.csv')
with open(out, 'w', newline='') as f:
    w = csv.writer(f); w.writerow(['date', 'event', 'time_et', 'tier', 'note']); w.writerows(E)
print(len(E), 'rows', len({e[0] for e in E}), 'distinct days ->', os.path.normpath(out))
